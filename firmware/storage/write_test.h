/*
 * The first write the firmware can make, and the proof that it landed.
 *
 * Everything below this file has been host-proven for months: the block layer
 * writes, the transaction engine stages and commits, `vfs_rw` journals. What
 * was missing is a caller -- an image that actually writes and then checks what
 * the medium holds. This is that caller, kept deliberately small so it can be
 * read in one sitting.
 *
 * What it does, in order:
 *
 *   1. refuses to run unless the caller mounted the volume (MOUNT);
 *   2. asks the D-57 gate to open the volume for writing, and stops with the
 *      gate's own error if the volume does not carry
 *      `/.helikon/write-enabled` (GATE) -- a normal volume refuses here and
 *      nothing has been written;
 *   3. replaces `/.helikon/write-test.txt` with a deterministic pattern of
 *      `length` bytes in one transaction, so the file is either the whole
 *      pattern or the previous contents (WRITE);
 *   4. reads the file back through the read-only VFS (READBACK);
 *   5. compares what came back with what it meant to write (VERIFY).
 *
 * Two rules it keeps:
 *
 *   - It never creates the opt-in file. If the gate refuses, that is the
 *     answer, not a puzzle to work around.
 *   - It never deletes its own file on failure. A test that cleans up after a
 *     bad write destroys the evidence with it; the file stays so a human can
 *     look at it through Disk Mode. A *successful* run is not silent either:
 *     the file remains, and running again replaces it, which is the second
 *     thing worth proving.
 *
 * The pattern is generated, not stored: byte `i` is `(uint8_t)(i * 31u + 7u)`.
 * That keeps the object at `HELIKON_WRITE_TEST_MAX` bytes of `.bss` instead of
 * twice that, and it means a bug in the compare cannot be hidden by comparing
 * two copies of the same buffer.
 *
 * Usage from a diagnostic image: mount, then
 * `helikon_write_test_run(&test, &storage, HELIKON_WRITE_TEST_BYTES)` and print
 * `helikon_write_stage_name(test.stage)` with the error when it returns
 * non-OK. Every failure names the stage it reached, because "write failed" is
 * not a report.
 */
#ifndef HELIKON_STORAGE_WRITE_TEST_H
#define HELIKON_STORAGE_WRITE_TEST_H

#include <stddef.h>
#include <stdint.h>

#include "helikon_error.h"
#include "mount.h"

/* Where the test file lives: beside the opt-in, inside the folder it needs. */
#define HELIKON_WRITE_TEST_PATH "/.helikon/write-test.txt"
/* 512 bytes is one sector and the smallest interesting catalog+extent change. */
#define HELIKON_WRITE_TEST_BYTES 512u
/* The largest pattern a single transaction can carry in one call. */
#define HELIKON_WRITE_TEST_MAX VFS_RW_IO_MAX

/* The stages, in the order they are reached. A report names the last one. */
#define HELIKON_WRITE_STAGE_NONE 0u
#define HELIKON_WRITE_STAGE_MOUNT 1u
#define HELIKON_WRITE_STAGE_GATE 2u
#define HELIKON_WRITE_STAGE_WRITE 3u
#define HELIKON_WRITE_STAGE_READBACK 4u
#define HELIKON_WRITE_STAGE_VERIFY 5u
#define HELIKON_WRITE_STAGE_DONE 6u

struct helikon_write_test {
    uint8_t actual[HELIKON_WRITE_TEST_MAX];
    uint32_t length;    /* bytes the run meant to write */
    uint32_t file_size; /* size the volume reported on read-back */
    int error;          /* HELIKON_OK, or the stage's error */
    uint8_t stage;      /* the last stage reached */
    uint8_t passed;     /* 1 only after VERIFY agreed */
};

/* The generated byte at `offset`. Exposed so a test can disagree with it. */
uint8_t helikon_write_pattern(uint32_t offset);

/* A short name for a stage, for a screen or a test failure. Never NULL. */
const char *helikon_write_stage_name(uint8_t stage);

/*
 * Runs the sequence above. `length` must be 1..HELIKON_WRITE_TEST_MAX.
 *
 * Returns HELIKON_OK only when the pattern was committed and read back
 * identical. Otherwise the first error, with `test->stage` naming where it
 * happened; `test->passed` stays 0. HELIKON_ERR_ARGUMENT means the caller
 * passed nothing mounted, a zero length or one above the maximum -- the volume
 * was not touched.
 */
int helikon_write_test_run(struct helikon_write_test *test,
                           struct helikon_storage *storage, uint32_t length);

#endif
