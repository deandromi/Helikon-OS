"""Build the signed staged-update fixtures for `tests/update`.

The firmware's staged-update client verifies a set before it writes anything, so
the test needs sets that really are signed: a verifier exercised only against
hand-made bytes proves nothing about its Ed25519 path. Signing needs a private
key, and no private key belongs in this repository or in the firmware, so the
sets are minted here, once, from a throwaway seed, and committed as bytes.

The seed is a fixed constant. Anyone can re-run this script and get the same
files, the same public key and the same signatures — which is the point of a
fixture, and exactly why the key it derives must never be used for anything but
this test.

    python3 tests/update/make_update_set.py            # write the fixtures
    python3 tests/update/make_update_set.py --check    # verify what is on disk

`--check` is what CI could run if the fixtures ever drifted; the files are small
(8 KiB of image), so they are committed rather than generated at build time: a
test that needs Python and `cryptography` to run is a test that does not run
everywhere.
"""

import argparse
import hashlib
import os
import struct
import sys

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

HERE = os.path.dirname(os.path.abspath(__file__))
FIXTURES = os.path.join(HERE, "fixtures")

# A fixture key, minted for this file only. Never use it for a real image.
SEED = bytes(range(0x40, 0x60))

MANIFEST_SIZE = 256
MANIFEST_SIGNED = 192
LOAD_ADDRESS = 0x08000000
BOARD_6G = 6
BOARD_7G = 7
KEY_ID = 0x4D505531  # "MPU1", matching the key id in the generated header
IMAGE_SIZE = 8192


def image_bytes(version):
    """A deterministic 8 KiB payload: two 4 KiB chunks, so the copy loops twice."""
    payload = bytearray(IMAGE_SIZE)
    for index in range(IMAGE_SIZE):
        payload[index] = (index * 37 + version * 11 + 5) & 0xFF
    # A recognisable header, so a dump of an installed image is obvious.
    payload[0:8] = b"HELIKON\x00"
    struct.pack_into("<I", payload, 8, version)
    return bytes(payload)


def build_manifest(image, board, version, key_id, *, development=False,
                   declared_size=None, declared_hash=None):
    manifest = bytearray(MANIFEST_SIZE)
    manifest[0:8] = b"HELIKON1"
    struct.pack_into("<I", manifest, 8, 1)                      # format version
    struct.pack_into("<I", manifest, 12, board)
    struct.pack_into("<I", manifest, 16, version)
    struct.pack_into("<I", manifest, 20, LOAD_ADDRESS)
    struct.pack_into("<I", manifest, 24,
                     len(image) if declared_size is None else declared_size)
    struct.pack_into("<I", manifest, 28, key_id)
    manifest[32:64] = (hashlib.sha256(image).digest()
                       if declared_hash is None else declared_hash)
    struct.pack_into("<I", manifest, 64, 1 if development else 0)
    return bytes(manifest)


def sign(manifest, key):
    signed = bytearray(manifest)
    signed[MANIFEST_SIGNED:MANIFEST_SIZE] = b"\x00" * (MANIFEST_SIZE - MANIFEST_SIGNED)
    signature = key.sign(bytes(signed[0:MANIFEST_SIGNED]))
    signed[MANIFEST_SIGNED:MANIFEST_SIZE] = signature
    return bytes(signed)


def public_key_bytes(key):
    return key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw)


def render_header(public_key):
    lines = [
        "/* SPDX-License-Identifier: CC0-1.0 */",
        "/*",
        " * The fixture public key for tests/update. Generated by",
        " * make_update_set.py from a fixed throwaway seed; never use it for a real",
        " * image, and never commit the seed's private key anywhere.",
        " */",
        "#ifndef HELIKON_TESTS_UPDATE_KEY_H",
        "#define HELIKON_TESTS_UPDATE_KEY_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define UPDATE_TEST_KEY_ID 0x{KEY_ID:08x}u",
        "",
        "static const uint8_t update_test_public_key[32] = {",
    ]
    for start in range(0, 32, 8):
        chunk = ", ".join(f"0x{byte:02x}" for byte in public_key[start:start + 8])
        lines.append(f"    {chunk},")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def build_sets(key):
    """name -> (manifest bytes, image bytes), keyed by fixture file stem."""
    v2 = image_bytes(2)
    v3 = image_bytes(3)
    sets = {}
    sets["good"] = (sign(build_manifest(v2, BOARD_6G, 2, KEY_ID), key), v2)
    sets["next"] = (sign(build_manifest(v3, BOARD_6G, 3, KEY_ID), key), v3)

    # A manifest whose hash is of different bytes: the set is signed and
    # well formed, and its image is not the one it names.
    other = image_bytes(9)
    sets["bad-hash"] = (
        sign(build_manifest(v2, BOARD_6G, 2, KEY_ID,
                            declared_hash=hashlib.sha256(other).digest()), key),
        v2)

    # Signed, well formed, for a different board.
    sets["wrong-board"] = (
        sign(build_manifest(v2, BOARD_7G, 2, KEY_ID), key), v2)

    # A correct manifest whose signature field was flipped after signing.
    good_manifest = bytearray(sign(build_manifest(v2, BOARD_6G, 2, KEY_ID), key))
    good_manifest[MANIFEST_SIGNED] ^= 0x01
    sets["bad-signature"] = (bytes(good_manifest), v2)

    # Signed as development-only, for the test that a release build refuses it.
    # Every other set is a release set: that is what an update really is.
    sets["development"] = (
        sign(build_manifest(v2, BOARD_6G, 2, KEY_ID, development=True), key), v2)

    # A manifest that declares more bytes than the image has.
    sets["short-image"] = (
        sign(build_manifest(v2, BOARD_6G, 2, KEY_ID,
                            declared_size=len(v2) + 4096), key), v2)

    # The same version as "good": the second install must be refused as a
    # downgrade (equal is not an upgrade).
    sets["same-version"] = (sets["good"][0], image_bytes(2))
    return sets


def write_fixtures(sets, header):
    os.makedirs(FIXTURES, exist_ok=True)
    written = []
    for name, (manifest, image) in sorted(sets.items()):
        # `same-version` reuses good's manifest byte for byte; write it anyway so
        # the test reads one directory without special cases.
        manifest_path = os.path.join(FIXTURES, f"{name}.manifest")
        image_path = os.path.join(FIXTURES, f"{name}.img")
        with open(manifest_path, "wb") as handle:
            handle.write(manifest)
        with open(image_path, "wb") as handle:
            handle.write(image)
        written += [manifest_path, image_path]
    header_path = os.path.join(HERE, "update_test_key.h")
    with open(header_path, "w", encoding="utf-8") as handle:
        handle.write(header)
    written.append(header_path)
    return written


def check_fixtures(sets, header):
    problems = []
    for name, (manifest, image) in sorted(sets.items()):
        for path, expected in ((os.path.join(FIXTURES, f"{name}.manifest"), manifest),
                               (os.path.join(FIXTURES, f"{name}.img"), image)):
            try:
                with open(path, "rb") as handle:
                    actual = handle.read()
            except OSError as error:
                problems.append(f"{path}: {error}")
                continue
            if actual != expected:
                problems.append(f"{path}: differs from what the generator builds")
    header_path = os.path.join(HERE, "update_test_key.h")
    try:
        with open(header_path, "r", encoding="utf-8") as handle:
            if handle.read() != header:
                problems.append(f"{header_path}: differs from what the generator builds")
    except OSError as error:
        problems.append(f"{header_path}: {error}")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the committed fixtures instead of writing")
    args = parser.parse_args()

    key = Ed25519PrivateKey.from_private_bytes(SEED)
    header = render_header(public_key_bytes(key))
    sets = build_sets(key)

    if args.check:
        problems = check_fixtures(sets, header)
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            return 1
        print(f"tests/update: {len(sets)} fixtures and the key header are current")
        return 0

    written = write_fixtures(sets, header)
    for path in written:
        print(os.path.relpath(path))
    print(f"tests/update: wrote {len(written)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
